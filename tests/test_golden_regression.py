"""Regression: the refactored package must reproduce the original scripts' numbers.

`tests/data/golden_bounds.json` was generated by running the original research
scripts (covariates_compare.py, tightness_graph_proof.py, mediator+confounder.py)
before the refactor.  These are the numbers behind the figures in the papers, so
any change here is a change to published results.
"""
import json
import os

import pytest

from pocbounds import ConjecturePNS
from pocbounds.recursive import RecursivePNS

HERE = os.path.dirname(__file__)
GOLDEN = os.path.join(HERE, "data", "golden_bounds.json")

BOUNDS = ["lb", "ub", "lbx", "ubx", "lby", "uby", "lbxy", "ubxy"]
CLOSED_FORM = {"ConjecturePNS": ConjecturePNS}

with open(GOLDEN) as f:
    GOLDEN_DATA = json.load(f)

CASES = GOLDEN_DATA["cases"]


def _ids(prefix):
    return [f"{prefix}-{i}" for i in range(len(CASES))]


@pytest.mark.parametrize("case", CASES, ids=_ids("case"))
def test_closed_form_bounds_match_original(case):
    n, k, p, q = case["n"], case["k"], case["p"], case["q"]
    prob, yi, xj = case["prob"], case["yi"], case["xj"]

    for name, cls in CLOSED_FORM.items():
        obj = cls(n, k, p, q, prob, yi, xj)
        for b in BOUNDS:
            assert getattr(obj, b) == pytest.approx(
                case["expected"][name][b], abs=1e-12
            ), f"{name}.{b} changed (n={n}, k={k})"


@pytest.mark.parametrize("case", CASES, ids=_ids("rec"))
def test_recursive_baseline_matches_original(case):
    n, k, p, q = case["n"], case["k"], case["p"], case["q"]
    prob, yi, xj = case["prob"], case["yi"], case["xj"]

    obj = RecursivePNS(n, n, k, p, q, prob, yi, xj)
    for b in BOUNDS:
        assert getattr(obj, b) == pytest.approx(
            case["expected"]["RecursivePNS"][b], abs=1e-12
        ), f"RecursivePNS.{b} changed (n={n}, k={k})"


def test_golden_file_is_not_empty():
    assert len(CASES) >= 100
    n_values = sum(len(c["expected"]) * len(BOUNDS) for c in CASES)
    assert n_values >= 1500
